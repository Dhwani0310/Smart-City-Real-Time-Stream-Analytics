
import json
from pathlib import Path

from pyspark.sql import SparkSession
from pyspark.sql.functions import (
    col, from_json, expr, when, lit,
    count, sum as spark_sum, avg, greatest,
    least, round as spark_round
)
from pyspark.sql.types import (
    StructType, StructField, StringType,
    DoubleType, IntegerType
)

# --------------------------------------------------
# 1. Load student configuration
# --------------------------------------------------

PROJECT_DIR = Path(__file__).resolve().parents[1]
CONFIG_PATH = PROJECT_DIR / "student_config.json"

if not CONFIG_PATH.exists():
    CONFIG_PATH = PROJECT_DIR / "config" / "student_config.json"

with open(CONFIG_PATH, "r", encoding="utf-8") as f:
    config = json.load(f)

STUDENT_ID = config["student_id"]
TOPIC = config["topic_name"]
THRESHOLD = float(config["temperature_threshold"])

weights = config["weights"]
W_ANOMALY = float(weights["anomaly_pct"])
W_EXCESS = float(weights["temp_excess"])
W_ALERTS = float(weights["critical_alerts"])

ALERTS_PATH = str(PROJECT_DIR / "output" / "critical_alerts")
CHECKPOINT_PATH = str(PROJECT_DIR / "checkpoint" / "task6_risk_ranker")

# --------------------------------------------------
# 2. Spark session
# --------------------------------------------------

spark = (
    SparkSession.builder
    .appName("202126940028_Zone_Risk_Ranking")
    .master("local[2]")
    .getOrCreate()
)

spark.sparkContext.setLogLevel("WARN")

print("=" * 65)
print("STUDENT:", STUDENT_ID)
print("TASK 6: LIVE ZONE RISK RANKING")
print("Temperature threshold:", THRESHOLD)
print("Weights:", W_ANOMALY, W_EXCESS, W_ALERTS)
print("=" * 65)

# --------------------------------------------------
# 3. Explicit Kafka JSON schema
# --------------------------------------------------

schema = StructType([
    StructField("event_id", StringType(), True),
    StructField("sensor_id", StringType(), True),
    StructField("zone_id", StringType(), True),
    StructField("event_time", StringType(), True),
    StructField("temperature", DoubleType(), True),
    StructField("humidity", DoubleType(), True),
    StructField("traffic_count", IntegerType(), True),
    StructField("status", StringType(), True),
    StructField("student_id", StringType(), True)
])

# Schema of Task 5 critical-alert JSON files
alert_schema = StructType([
    StructField("sensor_id", StringType(), True),
    StructField("zone_id", StringType(), True),
    StructField("event_time", StringType(), True),
    StructField("breach_count", IntegerType(), True),
    StructField("severity", StringType(), True),
    StructField("temperature", DoubleType(), True)
])

# --------------------------------------------------
# 4. Read live Kafka stream
# --------------------------------------------------

kafka_stream = (
    spark.readStream
    .format("kafka")
    .option("kafka.bootstrap.servers", "localhost:9092")
    .option("subscribe", TOPIC)
    .option("startingOffsets", "latest")
    .option("maxOffsetsPerTrigger", 500)
    .option("failOnDataLoss", "false")
    .load()
)

events = (
    kafka_stream
    .selectExpr("CAST(value AS STRING) AS json_value")
    .select(from_json(col("json_value"), schema).alias("data"))
    .select("data.*")
    .withColumn("event_ts", expr("try_to_timestamp(event_time)"))
    .filter(
        col("event_id").isNotNull()
        & col("sensor_id").isNotNull()
        & col("zone_id").isNotNull()
        & col("event_ts").isNotNull()
        & col("temperature").isNotNull()
        & (col("student_id") == lit(STUDENT_ID))
    )
)

# --------------------------------------------------
# 5. Calculate risk components per zone
# --------------------------------------------------

zone_stats = (
    events
    .withColumn(
        "is_anomaly",
        when(col("temperature") > THRESHOLD, 1).otherwise(0)
    )
    .withColumn(
        "temperature_excess",
        greatest(col("temperature") - lit(THRESHOLD), lit(0.0))
    )
    .groupBy("zone_id")
    .agg(
        count("*").alias("total_events"),
        spark_sum("is_anomaly").alias("anomalous_events"),
        avg("temperature_excess").alias("avg_temp_excess")
    )
    .withColumn(
        "anomaly_pct",
        col("anomalous_events") / col("total_events") * 100.0
    )
)

# --------------------------------------------------
# 6. Normalize risk components and calculate score
# --------------------------------------------------

def show_risk_ranking(batch_df, batch_id):

    print("\n" + "=" * 85)
    print(f"STUDENT {STUDENT_ID} | RISK RANKING | BATCH {batch_id}")
    print("=" * 85)

    if batch_df.isEmpty():
        print("No events received in this batch.")
        return

    # Read actual critical alerts generated by Task 5
    if Path(ALERTS_PATH).exists():

        alerts_df = (
            spark.read
            .schema(alert_schema)
            .json(ALERTS_PATH)
            .filter(col("severity") == "CRITICAL")
            .groupBy("zone_id")
            .agg(count("*").alias("critical_alerts"))
        )

    else:
        alerts_df = spark.createDataFrame(
            [],
            StructType([
                StructField("zone_id", StringType(), True),
                StructField("critical_alerts", IntegerType(), True)
            ])
        )

    # Join zone statistics with actual critical-alert counts
    combined = (
        batch_df
        .join(alerts_df, on="zone_id", how="left")
        .fillna({"critical_alerts": 0})
    )

    normalized = (
        combined
        .withColumn(
            "norm_anomaly",
            least(col("anomaly_pct"), lit(100.0))
        )
        .withColumn(
            "norm_excess",
            least(col("avg_temp_excess") / lit(20.0) * 100.0, lit(100.0))
        )
        .withColumn(
            "norm_alerts",
            least(col("critical_alerts") / lit(10.0) * 100.0, lit(100.0))
        )
    )

    ranked = (
        normalized
        .withColumn(
            "risk_score",
            col("norm_anomaly") * lit(W_ANOMALY)
            + col("norm_excess") * lit(W_EXCESS)
            + col("norm_alerts") * lit(W_ALERTS)
        )
        .withColumn("risk_score", spark_round("risk_score", 2))
        .orderBy(col("risk_score").desc())
    )

    print("\nLIVE ZONE RISK RANKING:")
    ranked.select(
        "zone_id",
        "total_events",
        "anomalous_events",
        "anomaly_pct",
        "avg_temp_excess",
        "critical_alerts",
        "risk_score"
    ).show(50, truncate=False)

    print("Highest risk zone is shown in the first row.")
    print("=" * 85)


# --------------------------------------------------
# 7. Start streaming query with checkpoint
# --------------------------------------------------

query = (
    zone_stats.writeStream
    .queryName("student_zone_risk_ranking")
    .outputMode("complete")
    .foreachBatch(show_risk_ranking)
    .option("checkpointLocation", CHECKPOINT_PATH)
    .trigger(processingTime="10 seconds")
    .start()
)

print("Zone risk ranking query started.")
print("Checkpoint:", CHECKPOINT_PATH)

query.awaitTermination()
